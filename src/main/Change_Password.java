    private void jBtnChangeActionPerformed(ActionEvent evt) {
        if (!Session.isLoggedIn()) {
            JOptionPane.showMessageDialog(this, "No active session.", "Error",
                JOptionPane.ERROR_MESSAGE);
            return;
        }

        String oldPass = new String(jOld.getPassword());
        String newPass = new String(jNew.getPassword());
        String confirmPass = new String(jConfirm.getPassword());

        if (newPass.isEmpty() || confirmPass.isEmpty()) {
            JOptionPane.showMessageDialog(this, "New password cannot be empty.",
                "Change Password", JOptionPane.WARNING_MESSAGE);
            return;
        }
        if (!newPass.equals(confirmPass)) {
            JOptionPane.showMessageDialog(this, "New passwords do not match.",
                "Change Password", JOptionPane.WARNING_MESSAGE);
            return;
        }
        if (newPass.length() < 4) {
            JOptionPane.showMessageDialog(this,
                "New password must be at least 4 characters long.",
                "Change Password", JOptionPane.WARNING_MESSAGE);
            return;
        }

        PreparedStatement ps = null;
        ResultSet rs = null;
        try {
            Connection conn = Connect.getConnection();

            // 1. verify current password
            ps = conn.prepareStatement(
                "SELECT password_hash, salt FROM users WHERE user_id = ?");
            ps.setInt(1, Session.userId());
            rs = ps.executeQuery();
            if (!rs.next()) {
                JOptionPane.showMessageDialog(this, "User not found.", "Error",
                    JOptionPane.ERROR_MESSAGE);
                return;
            }
            String storedHash = rs.getString("password_hash");
            String salt = rs.getString("salt");
            if (!PasswordUtil.verify(salt, oldPass, storedHash)) {
                JOptionPane.showMessageDialog(this, "Current password is incorrect.",
                    "Change Password", JOptionPane.ERROR_MESSAGE);
                return;
            }
            closeQuietly(rs);
            closeQuietly(ps);

            // 2. write new salted hash
            String newSalt = PasswordUtil.randomSaltHex();
            String newHash = PasswordUtil.hash(newSalt, newPass);

            ps = conn.prepareStatement(
                "UPDATE users SET password_hash = ?, salt = ?, must_change_password = 0 "
                + "WHERE user_id = ?");
            ps.setString(1, newHash);
            ps.setString(2, newSalt);
            ps.setInt(3, Session.userId());
            ps.executeUpdate();

            JOptionPane.showMessageDialog(this, "Password changed successfully.",
                "Change Password", JOptionPane.INFORMATION_MESSAGE);

            this.dispose();
            if (forced) {
                new Pharmacy().setVisible(true);
            }
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this,
                "Database error: " + ex.getMessage(),
                "Error", JOptionPane.ERROR_MESSAGE);
        } finally {
            closeQuietly(rs);
            closeQuietly(ps);
        }
    }

    private void jBtnCancelActionPerformed(ActionEvent evt) {
        if (forced) {
            int choice = JOptionPane.showConfirmDialog(this,
                "You must change your password to continue. Exit the application?",
                "Change Password", JOptionPane.YES_NO_OPTION,
                JOptionPane.WARNING_MESSAGE);
            if (choice == JOptionPane.YES_OPTION) {
                Session.logout();
                System.exit(0);
            }
        } else {
            this.dispose();
        }
    }

    private static void closeQuietly(AutoCloseable resource) {
        if (resource != null) {
            try {
                resource.close();
            } catch (Exception ignore) {
                // ignore
            }
        }
    }
