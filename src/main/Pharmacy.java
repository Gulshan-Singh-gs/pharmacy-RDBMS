    private JButton makeNavButton(String text, Class<? extends JFrame> type) {
        JButton button = new JButton(text);
        button.addActionListener(e -> openFrame(type));
        return button;
    }

    /**
     * Brings an existing window of the given type to the front, or creates a
     * new one if none is currently displayable.
     */
    private void openFrame(Class<? extends JFrame> type) {
        for (Window window : Window.getWindows()) {
            if (window instanceof JFrame && type.isInstance(window) && window.isDisplayable()) {
                JFrame frame = (JFrame) window;
                frame.setVisible(true);
                frame.toFront();
                return;
            }
        }
        try {
            Constructor<? extends JFrame> ctor = type.getDeclaredConstructor();
            JFrame frame = ctor.newInstance();
            frame.setVisible(true);
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this,
                "Could not open module: " + ex.getMessage(),
                "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

    private void logout() {
        Session.logout();
        this.dispose();
        new Login().setVisible(true);
    }
