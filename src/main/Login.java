    private void jBtnLoginActionPerformed(ActionEvent evt) {
        String username = jUsername.getText().trim();
        String password = new String(jPassword.getPassword());

        if (username.isEmpty() || password.isEmpty()) {
            JOptionPane.showMessageDialog(this,
                "Please enter username and password.",
                "Login", JOptionPane.WARNING_MESSAGE);
            return;
        }

        PreparedStatement ps = null;
        ResultSet rs = null;
        try {
            Connection conn = Connect.getConnection();
            ps = conn.prepareStatement(
                "SELECT user_id, name, password_hash, salt, must_change_password "
                + "FROM users WHERE name = ?");
            ps.setString(1, username);
            rs = ps.executeQuery();

            if (!rs.next()) {
                recordLogin(username, "FAILURE");
                JOptionPane.showMessageDialog(this,
                    "Invalid username or password.", "Login failed",
                    JOptionPane.ERROR_MESSAGE);
                return;
            }

            int userId = rs.getInt("user_id");
            String storedHash = rs.getString("password_hash");
            String salt = rs.getString("salt");
            boolean mustChange = rs.getBoolean("must_change_password");

            if (!PasswordUtil.verify(salt, password, storedHash)) {
                recordLogin(username, "FAILURE");
                JOptionPane.showMessageDialog(this,
                    "Invalid username or password.", "Login failed",
                    JOptionPane.ERROR_MESSAGE);
                return;
            }

            recordLogin(username, "SUCCESS");
            Session.login(userId, rs.getString("name"));

            this.dispose();
            if (mustChange) {
                new Change_Password(true).setVisible(true);
            } else {
                new Pharmacy().setVisible(true);
            }
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this,
                "Database error: " + ex.getMessage(),
                "Error", JOptionPane.ERROR_MESSAGE);
        } finally {
            closeQuietly(rs);
            closeQuietly(ps);
        }
    }

    private void jBtnCancelActionPerformed(ActionEvent evt) {
        System.exit(0);
    }

    /** Records a login event; never closes the shared connection. */
    private void recordLogin(String name, String type) throws SQLException {
        Connection conn = Connect.getConnection();
        PreparedStatement ps = null;
        try {
            ps = conn.prepareStatement(
                "INSERT INTO login_log (name, type, login_date, login_time) "
                + "VALUES (?, ?, CURDATE(), CURTIME())");
            ps.setString(1, name);
            ps.setString(2, type);
            ps.executeUpdate();
        } finally {
            closeQuietly(ps);
        }
    }

    private static void closeQuietly(AutoCloseable resource) {
        if (resource != null) {
            try {
                resource.close();
            } catch (Exception ignore) {
                // closing a released resource is a non-event
            }
        }
    }
